"""
Корректный запуск дев-сервера с авто-перезагрузкой.

Почему не просто `uvicorn --reload`: reload по умолчанию следит за ВСЕМ деревом,
включая `data/tenants/<tid>/workspace/`, куда агенты пишут код (bot.py, сайт).
Любая запись файла агентом перезапускала сервер и РОНЯЛА идущий офис-цикл прямо
посреди работы (в проде: «после запуска бота система крашнулась и перезагрузилась»).

⚠️ Реальный баг, обнаруженный 2026-07-07 (лог показал ~18 самовосстановлений
офиса за сессию, «хаос» после появления скриптов-парсеров, которые агенты
пишут в workspace): прежние reload_excludes вида "data/*"/"data/**/*" НЕ
исключали вложенные файлы вообще. uvicorn.FileFilter решает, паттерн это
директория или маска, вызовом `Path(pattern).is_dir()` НА САМОЙ СТРОКЕ
паттерна — а "data/*" не существует как литеральная директория, поэтому
попадает не в exclude_dirs (сравнение "это предок пути" — работает на любую
глубину), а в список масок, где сверяется через `PurePath.match()` — тот
матчит только столько последних компонент пути, сколько их в паттерне (2 для
"data/*"), и никогда не совпадает с файлом на глубине 5 уровней вроде
data/tenants/<tid>/workspace/<proj>/t1.py. Итог: запись файла агентом ВСЁ
РАВНО перезапускала сервер, несмотря на список excludes, — ровно тот баг,
который этот скрипт должен был предотвращать.

Fix: передаём АБСОЛЮТНЫЕ пути реальных директорий (не строки-маски) — тогда
`Path(...).is_dir()` истинно, паттерн уходит в exclude_dirs, и там же
сравнение "предок пути" работает на любую вложенность корректно.

Здесь reload следит только за исходниками проекта и игнорирует рабочие данные
тенантов, кеши и выгрузки. Запуск: `python scripts/run.py` (порт можно задать через
переменную окружения PORT).
"""

import os
from pathlib import Path

import uvicorn

if __name__ == "__main__":
    _root = Path(__file__).resolve().parent.parent
    # Абсолютные пути каталогов (не маски!) — см. докстринг выше про то, почему
    # маски вроде "data/*" не работают для вложенных путей.
    _exclude_dirs = [str(_root / d) for d in ("data", "graphify-out", "static", "webapp") if (_root / d).is_dir()]

    uvicorn.run(
        "server:app",
        host=os.getenv("HOST", "127.0.0.1"),
        port=int(os.getenv("PORT", "8000")),
        reload=True,
        # Следим только за кодом — не за данными тенантов, куда пишут агенты.
        reload_dirs=["src", "."],
        reload_includes=["*.py"],
        reload_excludes=[*_exclude_dirs, "*.json", "*.jsonl", "*.log", "*.txt"],
    )
