"""
Корректный запуск дев-сервера с авто-перезагрузкой.

Почему не просто `uvicorn --reload`: reload по умолчанию следит за ВСЕМ деревом,
включая `data/tenants/<tid>/workspace/`, куда агенты пишут код (bot.py, сайт).
Любая запись файла агентом перезапускала сервер и РОНЯЛА идущий офис-цикл прямо
посреди работы (в проде: «после запуска бота система крашнулась и перезагрузилась»).

Здесь reload следит только за исходниками проекта и игнорирует рабочие данные
тенантов, кеши и выгрузки. Запуск: `python scripts/run.py` (порт можно задать через
переменную окружения PORT).
"""

import os
import uvicorn

if __name__ == "__main__":
    uvicorn.run(
        "server:app",
        host=os.getenv("HOST", "127.0.0.1"),
        port=int(os.getenv("PORT", "8000")),
        reload=True,
        # Следим только за кодом — не за данными тенантов, куда пишут агенты.
        reload_dirs=["src", "."],
        reload_includes=["*.py"],
        reload_excludes=[
            "data/*", "data/**/*",            # рабочие папки тенантов (код агентов, сайты)
            "graphify-out/*", "graphify-out/**/*",
            "static/*", "static/**/*",         # билд фронтенда
            "webapp/*", "webapp/**/*",         # исходники фронта (свой dev-сервер)
            "*.json", "*.jsonl", "*.log", "*.txt",
        ],
    )
