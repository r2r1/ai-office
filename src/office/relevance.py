"""
Relevance — дешёвая структурная проверка «относится ли новая работа к ЭТОМУ
бизнесу клиента» (BOS §4, World Model).

Реальный найденный баг (форензик-аудит прогона 2026-07-18, тенант «Кухни на
заказ КМВ»): служебный запрос владельца платформы («построй график курса
доллара») CEO принял как полноценную бизнес-инициативу — отдельный Project,
найм двух агентов, повторяющийся процесс — хотя бриф клиента (niche="Кухни на
заказ...") был у модели в контексте (brief_block всегда в company_system).
Наличие ниши в промпте НЕ гарантирует, что модель сверится с ней перед
решением — LLM-инструкция это не структурный гейт.

Здесь — код-уровневый бэкстоп поверх LLM-решения (defense in depth, не замена
промпту): эмбеддинги короткие и дешёвые (строка, не документ; нет output-
токенов). Деградирует к «пропустить, не блокировать» при недоступности
эмбеддингов (core/embeddings.py уже возвращает None на любую ошибку) —
молчаливый провайдер не должен ронять принятие инициативы.

⚠️ Намеренно НЕТ здесь проверки «пересекается ли инициатива с уже идущим
Work» (тот же прогон показал и такой баг — два параллельных сайта под одну
задачу «витрина доверия»). Проверено и откинуто: калибровка на реальных
данных того же прогона показала, что cosine коротких текстов title+goal НЕ
разделяет надёжно "два проекта об одном и том же" от "два никак не связанных
проекта" — реальная пара-дубликат дала 0.256, а заведомо НЕСВЯЗАННАЯ пара дала
0.40, ВЫШЕ. Автоматика на таком сигнале ошибалась бы чаще, чем помогала.
Задача решена ЛУЧШЕ подходящим инструментом — LLM теперь видит полный текст
портфеля проектов (prompt_builder.portfolio_block) ПЕРЕД тем, как предложить
новую инициативу (см. orchestrator.generate_initiative/interpret_dashboard_
request), и судит по смыслу, а не по одному числу постфактум. Собственно
site-специфичное пересечение (два лендинга одновременно) по-прежнему ловится
структурно в routers/work.py (reused_site_project, факт "уже трогает site/")
— это не эмбеддинги, и трогать это не нужно.
"""

from src.core import embeddings

# Ниже порога — инициатива, похоже, не про бизнес клиента (off-brief). Выше —
# явно про него. Между — не хватает сигнала ни в одну сторону, не блокируем
# (порог занижен намеренно: ложное "не по теме" хуже, чем пропущенный кейс —
# решение остаётся за CEO/владельцем, здесь только маркировка для UI).
#
# Калибровка на реальных данных прогона 2026-07-18 (тенант «Кухни на заказ
# КМВ»): "курс USD/RUB" против брифа кухонь — 0.106; тексты задач самого
# бизнеса кухонь против того же брифа — 0.256–0.48. Разрыв чёткий и
# воспроизводимый — порог 0.15 уверенно разделяет "не про бизнес" от "про
# бизнес", даже с запасом.
OFF_BRIEF_THRESHOLD = 0.15


def _brief_text() -> str:
    from src.office import brief as brief_module
    b = brief_module.get() or {}
    parts = [b.get("niche", ""), b.get("audience", ""), b.get("goal", ""), b.get("summary", "")]
    return " ".join(p for p in parts if p).strip()


def brief_similarity(text: str) -> float | None:
    """Косинусное сходство текста инициативы с брифом клиента (niche+audience+
    goal+summary). None — эмбеддинги недоступны (сеть/баланс/провайдер) —
    вызывающий код обязан деградировать к «не блокировать», не считать это
    сигналом off-brief."""
    brief_text = _brief_text()
    if not brief_text or not (text or "").strip():
        return None
    v_text = embeddings.embed(text, agent_id="relevance_check")
    v_brief = embeddings.embed(brief_text, agent_id="relevance_check")
    if v_text is None or v_brief is None:
        return None
    return embeddings.cosine(v_text, v_brief)


def is_off_brief(text: str) -> bool:
    """True — инициатива структурно не похожа на бизнес клиента (см.
    OFF_BRIEF_THRESHOLD). False и при явном совпадении, И при недоступных
    эмбеддингах (см. brief_similarity) — не блокируем на неуверенности."""
    sim = brief_similarity(text)
    return sim is not None and sim < OFF_BRIEF_THRESHOLD
