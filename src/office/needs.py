"""
Единый скорер потребностей (BOS §5: «общий скорер потребностей — один, не два»).

Skills и Tool Router решают одну и ту же задачу: сматчить свободный текст
потребности («опубликовать лендинг», «премиальный сайт БЕЗ 3D») со способом её
закрыть (скилл / интеграция+действие). Раньше у каждого был СВОЙ скорер:
обработка отрицания («без 3D») жила только в скиллах, токенизация — только в
роутере, и поведение матчинга расходилось. Примитивы собраны здесь; доменные
надстройки (intent-хинты роутера, фильтр по ролям у скиллов) остаются в своих
модулях — это данные, а не логика скоринга.
"""

import re

_STOP = {"мне", "нужно", "нужен", "надо", "хочу", "для", "это", "что", "как",
         "the", "a", "to", "of", "in"}


def tokens(s: str) -> set[str]:
    """Ключевые токены свободного текста: без стоп-слов и слов короче 3 символов."""
    words = re.split(r"[^\wа-яё]+", (s or "").lower())
    return {w for w in words if len(w) > 2 and w not in _STOP}


def score_keywords(need: str, keywords: list[str]) -> int:
    """
    Насколько текст потребности совпадает с ключевыми словами способа
    (число совпадений). Учитывает отрицание: «премиальный сайт БЕЗ 3D» содержит
    «3d» как подстроку и раньше засчитывался В ПОЛЬЗУ 3D-скилла (реальный кейс —
    designer просил «без 3D», а use_skill выдал framer_motion_3d_site). Ключевое
    слово, которому непосредственно предшествует «без »/«не », штрафуется —
    конкурирующий способ выигрывает матч.
    """
    t = (need or "").lower()
    total = 0
    for k in keywords:
        idx = t.find(k)
        if idx == -1:
            continue
        prefix = t[max(0, idx - 6):idx]
        if "без " in prefix or "не " in prefix:
            total -= 1
        else:
            total += 1
    return total


def overlap(need: str, capability_tokens: set[str]) -> float:
    """Пересечение токенов потребности с токенами описания способности (роутер),
    нормализованное по объёму объединения (Jaccard). Раньше был сырой count —
    способность с длинным description (много токенов в имени/description/action)
    получала случайные совпадения "бесплатно": чем больше токенов, тем выше шанс
    задеть слово из потребности даже нерелевантно, и score "прыгал" непредсказуемо
    при росте реестра интеграций. Jaccard штрафует широкие множества токенов за
    неспецифичность. Шкала *10 — чтобы остаться в том же порядке величины, что
    старый int-count, и не ломать порог tool_router.best()."""
    need_t = tokens(need)
    if not need_t or not capability_tokens:
        return 0.0
    inter = need_t & capability_tokens
    if not inter:
        return 0.0
    union = need_t | capability_tokens
    return round(len(inter) / len(union) * 10, 2)


# «бот» как ГОЛАЯ подстрока опасен: это корень слов «раБОТать», «доработать»,
# «обработать», «заработать» — любая обычная задача вроде «доработать оффер и
# CTA» ложно матчилась как Telegram-бот. Реальный прод-инцидент: auto-generated
# gap-задача marketer'а «Усилить привлечение заявок: доработать оффер и CTA…»
# сама содержала слово «доработать» → plan._derive_artifacts пометил её как
# artifact=bot → acceptance потребовала bot.py с aiogram/BOT_TOKEN → 3 провала
# → задача заблокирована → у отдела не осталось другой работы → офис замер.
# «бот» матчится только когда ему НЕ предшествует кириллическая буква (т.е. это
# начало слова/корня — «бот», «бота», «боту», «чат-бот», «телеграм-бот»), но не
# когда «бот» — середина другого слова («работать», «доработать»).
_BOT_RE = re.compile(r"telegram|aiogram|chatbot|чат-бот|телеграм|(?<![а-яё])бот")


def is_bot_reference(text: str) -> bool:
    """Упоминание Telegram-бота в тексте — единственная точка проверки (см.
    предупреждение выше про подстроку «бот»/«работать»)."""
    return bool(_BOT_RE.search((text or "").lower()))


# Реальный найденный баг (живой прогон): _derive_artifacts по умолчанию считает
# ЛЮБУЮ задачу developer'а сайт-задачей (artifact=site) — верно для большинства
# задач, но не для фоновых скриптов/процессов (create_recurring_process,
# record_metric, разовый парсер курса валют и т.п.), которые вообще не трогают
# site/. Ложное artifact=site заставляло routers/work.py:accept_initiative
# считать такую инициативу «тоже про сайт» (touches_site) и молча дозаписывать
# её задачи в ЧУЖОЙ, уже активный сайт-проект вместо своего — принятая
# инициатива («Автообновление курса USD/RUB») выглядела так, будто вообще не
# создала проект. Тот же принцип, что у _BOT_RE: матчим специфичные маркеры
# фоновой работы, не бытовые слова, которые могут встретиться где угодно.
_PROCESS_RE = re.compile(
    r"create_recurring_process|record_metric|повторяющ\w* процесс|"
    r"фоновы\w* (?:скрипт|процесс)|cron-?job"
)


def is_process_reference(text: str) -> bool:
    """Упоминание фонового скрипта/повторяющегося процесса — задача НЕ про site/,
    даже если исполнитель developer (см. _derive_artifacts в plan.py)."""
    return bool(_PROCESS_RE.search((text or "").lower()))
